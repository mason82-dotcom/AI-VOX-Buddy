#!/usr/bin/env python3
"""Converts a PSF console font (8x16) to main/font/font8x16.c (ASCII 0x20..0x7e).

Default source: Terminus Font (bold), SIL OFL 1.1, from Debian's console-setup.
Usage: scripts/gen-font.py [/usr/share/consolefonts/Lat15-TerminusBold16.psf.gz]
"""
import gzip
import os
import struct
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-TerminusBold16.psf.gz"
data = gzip.open(src).read() if src.endswith(".gz") else open(src, "rb").read()

if data[:2] == b"\x36\x04":                       # PSF1
    mode, height = data[2], data[3]
    count, width, offset, glyph_bytes = (512 if mode & 1 else 256), 8, 4, data[3]
    table = mode & 2
    def entries(pos):
        while pos + 2 <= len(data):
            yield pos
            pos += 2
else:                                              # PSF2
    magic, _, offset, flags, count, glyph_bytes, height, width = struct.unpack_from("<8I", data)
    assert magic == 0x864AB572, "not a PSF font"
    table = flags & 1
assert width == 8 and height == 16, f"need 8x16, got {width}x{height}"

glyphs = [data[offset + i * glyph_bytes: offset + (i + 1) * glyph_bytes] for i in range(count)]
mapping = {}
if table:
    pos = offset + count * glyph_bytes
    if data[:2] == b"\x36\x04":
        for index in range(count):
            while True:
                (cp,) = struct.unpack_from("<H", data, pos); pos += 2
                if cp == 0xFFFF: break
                if cp != 0xFFFE: mapping.setdefault(cp, index)
    else:
        for index in range(count):
            end = data.index(b"\xff", pos)
            # Single code points precede the first 0xFE sequence separator.
            for ch in data[pos:end].split(b"\xfe")[0].decode("utf-8", "replace"):
                mapping.setdefault(ord(ch), index)
            pos = end + 1
else:
    mapping = {cp: cp for cp in range(count)}

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "font", "font8x16.c")
with open(out, "w") as f:
    f.write("/* Generated by scripts/gen-font.py from %s.\n" % os.path.basename(src))
    f.write(" * Terminus Font: Copyright (c) 2010 Dimitar Toshkov Zhekov,\n")
    f.write(" * licensed under the SIL Open Font License 1.1 (see OFL-Terminus.txt). */\n")
    f.write('#include <stdint.h>\n\n/* ASCII 0x20..0x7e, 16 rows per glyph, MSB = leftmost pixel. */\n')
    f.write("const uint8_t font8x16[95][16] = {\n")
    for cp in range(0x20, 0x7F):
        g = glyphs[mapping[cp]] if cp in mapping else bytes(16)
        f.write("    {%s}, /* %r */\n" % (", ".join("0x%02x" % b for b in g[:16]), chr(cp)))
    f.write("};\n")
print("wrote", os.path.normpath(out))
